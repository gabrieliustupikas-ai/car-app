// Generates the ranks reference data from the single source of truth in packages/core/src/levels.ts
// Usage: node scripts/generate-ranks-sql.mjs > supabase/migrations/20261117000005_reference_ranks.sql
import { RANKS, MAX_LEVEL, xpForLevel, levelForXp } from '../packages/core/src/levels.ts';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (let l = 1; l <= MAX_LEVEL; l++) {
  const info = levelForXp(xpForLevel(l));
  rows.push(`  (${l}, ${q(info.rank.key)}, ${q(info.rank.lt)}, ${q(info.rank.en)}, ${q(info.tier)}, ${xpForLevel(l)})`);
}
console.log(`-- ROADCLUB · 0005 · ranks (GENERATED by scripts/generate-ranks-sql.mjs from packages/core/src/levels.ts — do not edit)
insert into public.ranks (level, rank_key, name_lt, name_en, tier, xp_required) values
${rows.join(',\n')}
on conflict (level) do update set rank_key = excluded.rank_key, name_lt = excluded.name_lt, name_en = excluded.name_en,
  tier = excluded.tier, xp_required = excluded.xp_required;
-- ${RANKS.length} ranks × 5 tiers`);
